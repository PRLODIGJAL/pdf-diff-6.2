# ---- 叠加闪烁（2026-10-30 晚，替掉上一版的「自动摆动」）----
# 原话：「快速摆动相当于是手来回左右动，那有没有可能就是快速来回叠加呢？把这个
# 快速摆动给撤掉，改为快速叠加：这一刻是旧版本，下一刻是新版本，再下一刻又是
# 旧版，这样子来回叠加也是比较快速，这样的效果会更明显一点。」
# 为什么叠加比扫线更明显：扫线是**一条竖线从内容上划过**，改过的地方只在线经过的
# 那一瞬「跳」一下，其余时间它和没改一样；叠加是**整页在同一位置 A/B 轮换**，改过
# 的地方每一帧都在跳 —— 而没改的地方两帧完全重合、稳如石头，所以「跳的那一小块」
# 会自己跳出来。天文上找新星就是这么干的（同一块天区两张底片来回闪，冥王星是这么
# 发现的）。代价：叠加看不到「这两处是不是同一列/同一行」的上下文，只适合**定位**，
# 定位到了还得关掉叠加去看分割线版本。
# 间隔＝「一版停多久再翻成另一版」，一个完整循环 = 2 × 间隔。
# ⚠️ 2026-11-02 上午：删掉 0.6，整体提速（0.3→慢、0.15→中、0.08→快）。
