# ---- 滑动视图的性能（2026-10-30 晚实测后改的架构，见 `_render_swipe`）----
# 为什么不是「旧版 canvas 用 place 改宽度」：实测在 macOS/Tk 8.6 上**任何 widget
# 几何变化都会让整个 toplevel 重画**，成本只跟**窗口面积**成正比，与改多小无关：
#   1240×740 窗里挪一下 2px 的分割线 → 72ms（＝14fps）；同样窗口缩到 1080×560
#   → 46.7ms，正好是面积比 0.66。而**同一块 canvas 内部**移动图形（`coords`）
#   只要 0.24ms、切换图形显隐（`state`）只要 0.11ms —— 差 300 倍。
#   （对照实验还排除了「图太大」这个猜想：把画布高度从 476 压到 100、把图换成
#   同尺寸纯白、把图切成 11 条横带，耗时全都纹丝不动；窗口 withdraw 掉只剩
#   0.26ms —— 所以成本 100% 在「重画窗口」这一步，不在画图本身。）
# 所以改成：**一块 canvas 里放两张图**，旧版切成竖条，拖拽只切换条带的 state。
